"""Generates RadioSim/Game/BcPackTables.cs from a bcpack-rs checkout.

    python tools/gen_bcpack_tables.py <path to bcpack-rs>

Reads the rANS model tables (src/tables.rs, themselves generated from Microsoft's MIT-licensed
silicon-rans Verilog) and the BC7 control codes and dictionary (data/bc7.json).
bcpack-rs: https://github.com/Ahmet-Dedeler/bcpack-rs (MIT OR Apache-2.0), by Ahmet Dedeler.
"""
import json, re, sys, os

src = sys.argv[1]
out = os.path.join(os.path.dirname(__file__), '..', 'RadioSim', 'Game', 'BcPackTables.cs')
rs = open(os.path.join(src, 'src', 'tables.rs'), encoding='utf-8').read()
sha = re.search(r'TABLES_SHA256: &str = "([0-9a-f]+)"', rs).group(1)

def table(name):
    m = re.search(r'pub static ' + name + r': [^=]+= \[(.*?)\n\];', rs, re.S)
    nums = [int(x, 0) for x in re.findall(r'0x[0-9A-Fa-f]+|\d+', re.sub(r'//[^\n]*', '', m.group(1)))]
    assert len(nums) == 9 * 16 * 10, (name, len(nums))
    return nums

bc7 = json.load(open(os.path.join(src, 'data', 'bc7.json'), encoding='utf-8'))
control = bc7['control']
assert len(control) == 285 and len(bc7['dictionary']) == 255
subsets, ep, ix = [], [], []
for e in bc7['dictionary']:
    if e is None:
        subsets.append(0); ep += [0] * 24; ix += [0] * 32; continue
    subsets.append(e['subsets'] or 0)
    ep += [v or 0 for v in e['ep']]
    ix += [v or 0 for v in e['ix']]

def arr(ctype, name, vals, per=24):
    lines = [', '.join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f'    public static readonly {ctype}[] {name} =\n    {{\n        ' + ',\n        '.join(lines) + ',\n    };\n'

with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write(f'''// Generated by tools/gen_bcpack_tables.py from bcpack-rs (src/tables.rs, data/bc7.json). Do not edit.
// bcpack-rs by Ahmet Dedeler (https://github.com/Ahmet-Dedeler, https://ahmetdedeler.com)
// Source: https://github.com/Ahmet-Dedeler/bcpack-rs
// SPDX-License-Identifier: MIT OR Apache-2.0
// The rANS model tables come from mdu_minirans.v in https://github.com/microsoft/silicon-rans
// (MIT License, Copyright (c) Microsoft Corporation). bcpack-rs table hash: {sha}

namespace RadioSim.Game;

static class BcPackTables
{{
    // rANS models, flattened [eab][q][seg] (9 x 16 x 10)
''')
    for name, ctype in [('BASE_TABLE', 'ushort'), ('FREQ_TABLE', 'ushort'), ('RF_TABLE', 'uint'), ('RS_TABLE', 'byte'), ('RN_TABLE', 'ushort')]:
        f.write(arr(ctype, name.split('_')[0].capitalize(), table(name), 10))
    f.write('\n    // BC7 control codes: E, O, mode, partition, rotation, index selection\n')
    f.write(arr('byte', 'Bc7Control', [v for c in control for v in c], 6))
    f.write('\n    // BC7 dictionary (255 entries): subsets, endpoints (3 x R0 R1 G0 G1 B0 B1 A0 A1), indices (2 x 16)\n')
    f.write(arr('byte', 'Bc7DictSubsets', subsets, 32))
    f.write(arr('byte', 'Bc7DictEp', ep, 24))
    f.write(arr('byte', 'Bc7DictIx', ix, 32))
    f.write('}\n')
print('wrote', out)
